function generateEntryHtml(entry: Entry, entries: Entry[], relations: Relation[]): string {
  const relatedRelations = relations.filter(
    (r) => r.sourceEntryId === entry.id || r.targetEntryId === entry.id,
  )

  const relatedEntries = relatedRelations
    .map((r) => {
      const targetId = r.sourceEntryId === entry.id ? r.targetEntryId : r.sourceEntryId
      return entries.find((e) => e.id === targetId)
    })
    .filter(Boolean)

  return t(
    '<!DOCTYPE html>\n<html lang="zh-CN">\n<head>\n  <meta charset="UTF-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1.0">\n  <title>{0} - WDWorld</title>\n  <link rel="stylesheet" href="style.css">\n</head>\n<body>\n  <div class="container">\n    <header class="header">\n      <a href="index.html" class="logo">WDWorld</a>\n      <nav class="nav">\n        <a href="index.html">目录</a>\n      </nav>\n    </header>\n    \n    <main class="main">\n      <article class="entry">\n        <div class="entry-header">\n          <div class="entry-icon {1}">\n            <svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M16 21v-2a4 4 0 0 0-4-4H6a4 4 0 0 0-4 4v2"/><circle cx="9" cy="7" r="4"/><path d="M22 21v-2a4 4 0 0 0-3-3.87"/><path d="M16 3.13a4 4 0 0 1 0 7.75"/></svg>\n          </div>\n          <div>\n            <h1 class="entry-title">{2}</h1>\n            <span class="entry-type">{3}</span>\n          </div>\n        </div>\n        \n        {4}\n        \n        <div class="entry-content">\n          {5}\n        </div>\n        \n        {6}\n        \n        <footer class="entry-footer">\n          <span>创建于 {7}</span>\n          <span>更新于 {8}</span>\n        </footer>\n      </article>\n    </main>\n    \n    <footer class="footer">\n      <p>Generated by WDWorld</p>\n    </footer>\n  </div>\n</body>\n</html>',
    {
      0: escapeHtml(entry.title),
      1: entry.type,
      2: escapeHtml(entry.title),
      3: ENTRY_TYPE_LABELS[entry.type],
      4: entry.summary ? `<p class="entry-summary">${escapeHtml(entry.summary)}</p>` : '',
      5: contentToSafeHtml(entry.content),
      6:
        relatedEntries.length > 0
          ? `
        <div class="related-section">
          <h3>${t('相关条目')}</h3>
          <ul class="related-list">
            ${relatedEntries
              .map(
                (rel) => `
              <li><a href="${encodeURIComponent(rel!.slug)}.html">${escapeHtml(rel!.title)}</a></li>
            `,
              )
              .join('')}
          </ul>
        </div>
        `
          : '',
      7: entry.createdAt,
      8: entry.updatedAt,
    },
  )
}

function generateIndexHtml(entries: Entry[]): string {
  const groupedEntries = entries.reduce(
    (acc, entry) => {
      if (!acc[entry.type]) acc[entry.type] = []
      acc[entry.type].push(entry)
      return acc
    },
    {} as Record<string, Entry[]>,
  )

  return t(
    '<!DOCTYPE html>\n<html lang="zh-CN">\n<head>\n  <meta charset="UTF-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1.0">\n  <title>WDWorld - 目录</title>\n  <link rel="stylesheet" href="style.css">\n</head>\n<body>\n  <div class="container">\n    <header class="header">\n      <span class="logo">WDWorld</span>\n    </header>\n    \n    <main class="main">\n      <h1 class="title">百科目录</h1>\n      <p class="subtitle">共 {0} 条条目</p>\n      \n      <div class="category-list">\n        {1}\n      </div>\n    </main>\n    \n    <footer class="footer">\n      <p>Generated by WDWorld</p>\n    </footer>\n  </div>\n</body>\n</html>',
    {
      0: entries.length,
      1: Object.entries(groupedEntries)
        .map(([type, items]) => {
          return `
            <div class="category">
              <h2 class="category-title">
                <span class="category-icon ${type}">
                  <svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M16 21v-2a4 4 0 0 0-4-4H6a4 4 0 0 0-4 4v2"/><circle cx="9" cy="7" r="4"/><path d="M22 21v-2a4 4 0 0 0-3-3.87"/><path d="M16 3.13a4 4 0 0 1 0 7.75"/></svg>
                </span>
                ${ENTRY_TYPE_LABELS[type as EntryType]} (${items.length})
              </h2>
              <ul class="entry-list">
                ${items
                  .map(
                    (entry) => `
                  <li>
                    <a href="${encodeURIComponent(entry.slug)}.html">${escapeHtml(entry.title)}</a>
                    ${entry.summary ? `<span class="summary">${escapeHtml(entry.summary)}</span>` : ''}
                  </li>
                `,
                  )
                  .join('')}
              </ul>
            </div>
          `
        })
        .join(''),
    },
  )
}

